// ─── The X-ray binaries of the Milky Way ───────────────────────────────────────────────────────────────────────────
// One entry makes the hole and its binary (xrb below). Where a paper gives a 95 % interval, the 1σ drawn and shown is
// half of it over 1.96 and the note says so; where only a range is published, the hole is drawn at its middle and the
// card says that too (GX 339−4).

/**
 * A hole and its binary from one entry: the first table's two records (HoleJson and the system), with the card's notes
 * made from what is assumed (the orientation, or the orientation and the phase where no ephemeris is used) and what is
 * not drawn (the disc of gas between outbursts).
 */
function xrb(o) {
  const phaseAssumed = !o.orbit.T0JD;
  const spinCard = o.spin.value !== null ? spinLine(o.spin.value) : STELLAR_SPIN_LINE;
  const hole = {
    id: o.id,
    name: o.name,
    ...(o.shortName ? { shortName: o.shortName } : {}),
    aliases: o.aliases,
    class: 'stellar',
    placement: 'binary',
    constellation: o.constellation,
    mass: o.mass,
    ...(o.massNote ? { massNote: o.massNote } : {}),
    massMethod: 'its companion’s orbit',
    spin: o.spin,
    facts: o.facts,
    modelNotes: o.modelNotes ?? [spinCard, phaseAssumed ? XRB_PHASE_LINE : XRB_ORIENTATION_LINE, XRB_GAS_LINE],
    ...(o.sheetNotes?.length ? { sheetNotes: o.sheetNotes } : {}),
    ...(o.disk ? { disk: o.disk } : {}),
    refs: o.refs,
    fallAllowed: false,
    orbitLine: true,
  };
  const system = {
    id: `${o.id}-system`,
    name: `${o.name} system`,
    hole: o.id,
    astrometry: o.astrometry,
    distance: o.distance,
    astrometryRefs: o.astrometryRefs,
    ...(o.rvNote ? { rvNote: o.rvNote } : {}),
    star: { id: `${o.id}-star`, name: `${o.name}’s star`, catalogueIndex: null, ...o.star },
    orbit: { kind: 'xrb', ...o.orbit },
    assumed: o.assumed ?? (phaseAssumed ? XRB_PHASE_ASSUMED : XRB_ASSUMED),
  };
  return { hole, system };
}

